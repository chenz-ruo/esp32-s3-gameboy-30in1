#!/usr/bin/env python3
"""
gen_font_box.py - build the firmware's bitmap fonts from MiSans TTFs.

Scans main/*.c and main/*.h for every character actually used, rasterises it
at the requested pixel sizes with FreeType (via Pillow), quantises to 4 bpp
alpha and emits main/font_data.c.  Re-run after editing any UI string:

    python tools/gen_font_box.py        # from the repository root

Also writes build/preview_<font>.png so the glyph quality can be eyeballed.

Requires Pillow and the MiSans family installed in either C:/Windows/Fonts or
%LOCALAPPDATA%/Microsoft/Windows/Fonts.  The generated font_data.c is checked
in, so a normal firmware build needs neither Python nor the TTFs.
"""
import os
import re
import sys
import glob

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "main")
BUILD = os.path.join(ROOT, "build")

FONT_DIRS = [
    "C:/Windows/Fonts",
    os.path.join(os.environ.get("LOCALAPPDATA", ""), "Microsoft/Windows/Fonts"),
]


def font_path(name):
    for d in FONT_DIRS:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    return os.path.join(FONT_DIRS[0], name)

# name, ttf, px, charset, extra chars
# font_52 renders the large stimulus of the judgment games.  Its "digits"
# charset alone is not enough: seven games show CJK colour words and geometric
# symbols at 50 px, so those glyphs are listed explicitly in "extra".
SPECS = [
    ("font_14", "MiSans-Regular.ttf", 14, "all", ""),
    ("font_18", "MiSans-Regular.ttf", 18, "all", ""),
    ("font_28", "MiSans-Semibold.ttf", 28, "all", ""),
    ("font_52", "MiSans-Semibold.ttf", 50, "digits", "ms%GO红绿蓝←●▲■◆★○△□◇"),
]

LATIN = "".join(chr(c) for c in range(0x20, 0x7F))
DIGITS = "0123456789.,:+-/%()<>[]!"
SYMBOLS = "\u00b0\u00d7\u2022\u2192"  # degree, times, bullet, arrow


def collect_chars():
    """Every non-ASCII character appearing in the sources, plus all ASCII."""
    chars = set(LATIN)
    for path in glob.glob(os.path.join(SRC, "*.c")) + glob.glob(os.path.join(SRC, "*.h")):
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        # strip comments so deleted strings do not bloat the font
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        text = re.sub(r"//[^\n]*", "", text)
        for ch in text:
            if ord(ch) > 0x7F and ch.isprintable():
                chars.add(ch)
    return chars


def build_pool(glyphs, font):
    """Rasterise and pack. Returns (entries, pool_bytes)."""
    entries, pool = [], bytearray()
    for cp in sorted(glyphs):
        ch = chr(cp)
        mask = font.getmask(ch, mode="L")
        w, h = mask.size
        bbox = font.getbbox(ch)
        adv = int(round(font.getlength(ch)))
        bx, by_top = bbox[0], bbox[1]
        if w == 0 or h == 0:
            entries.append((cp, 0, 0, adv, 0, 0, 0))
            continue
        data = bytes(mask)
        stride = (w + 1) // 2
        packed = bytearray(stride * h)
        for y in range(h):
            for x in range(w):
                v = data[y * w + x]
                a = (v * 15 + 127) // 255
                if a:
                    idx = y * stride + (x >> 1)
                    if x & 1:
                        packed[idx] |= a
                    else:
                        packed[idx] |= a << 4
        off = len(pool)
        pool += packed
        entries.append((cp, w, h, adv, bx, by_top, off))
    return entries, pool


def emit(name, entries, pool, ascent, line_h, descender_note):
    out = []
    out.append("/* Auto-generated by tools/gen_font_box.py - do not edit. */")
    out.append('#include "font.h"')
    out.append("")
    out.append(f"static const uint8_t {name}_pool[] = {{")
    for i in range(0, len(pool), 20):
        out.append("    " + ",".join(str(b) for b in pool[i:i + 20]) + ",")
    out.append("};")
    out.append("")
    out.append(f"static const Glyph {name}_glyphs[] = {{")
    for (cp, w, h, adv, bx, by, off) in entries:
        out.append(f"    {{{cp},{w},{h},{adv},{bx},{by},{off}}},")
    out.append("};")
    out.append("")
    out.append(f"const Font {name} = {{ {name}_glyphs, {len(entries)}, {name}_pool, "
               f"{ascent}, {line_h} }};")
    out.append("")
    return "\n".join(out)


def preview(name, ttf, px, chars):
    img = Image.new("L", (480, 120), 0)
    d = ImageDraw.Draw(img)
    f = ImageFont.truetype(font_path(ttf), px)
    sample = "REFLEX 反应测试 0123456789 ms"
    d.text((4, 4), sample, font=f, fill=255)
    d.text((4, 60), "".join(sorted(chars, key=lambda c: ord(c))[40:90]), font=f, fill=255)
    os.makedirs(BUILD, exist_ok=True)
    img.save(os.path.join(BUILD, f"preview_{name}.png"))


def main():
    chars = collect_chars()
    cjk = {c for c in chars if ord(c) > 0x7F}
    print(f"source charset: {len(chars)} chars ({len(cjk)} non-ASCII)")

    parts = []
    for name, ttf, px, charset, extra in SPECS:
        path = font_path(ttf)
        if not os.path.exists(path):
            sys.exit(f"font missing: {path}")
        font = ImageFont.truetype(path, px)
        ascent, descent = font.getmetrics()
        glyph_chars = set()
        if charset == "latin":
            glyph_chars = set(LATIN) | set(SYMBOLS)
        elif charset == "all":
            glyph_chars = set(LATIN) | set(SYMBOLS) | cjk
        elif charset == "digits":
            glyph_chars = set(DIGITS) | set(SYMBOLS) | set("ABCDEFGHIJKLMNOPQRSTUVWXYZ") | set("ms")
        glyph_chars |= set(extra)
        # keep only what the renderer can actually draw
        ok = set()
        for ch in glyph_chars:
            try:
                font.getmask(ch, mode="L")
                ok.add(ord(ch))
            except Exception:
                pass
        # space must exist and be the lowest code point (fallback glyph)
        ok.add(0x20)
        entries, pool = build_pool(ok, font)
        line_h = ascent + descent
        print(f"{name}: {len(entries)} glyphs, pool {len(pool)} B, ascent {ascent}, line {line_h}")
        parts.append(emit(name, entries, pool, ascent, line_h, descent))
        preview(name, ttf, px, {chr(c) for c in ok})

    with open(os.path.join(SRC, "font_data.c"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))
    print("wrote main/font_data.c")


if __name__ == "__main__":
    main()
